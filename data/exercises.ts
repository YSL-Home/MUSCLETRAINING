export function getExerciseBySlug(slug: string): Exercise | undefined {
  return EXERCISES.find(e => e.slug === slug)
}

export function getExercisesByMuscle(muscleId: MuscleId): Exercise[] {
  return EXERCISES.filter(e => e.musclesPrimaires.includes(muscleId))
}

export function getExercisesByMuscleSecondary(muscleId: MuscleId): Exercise[] {
  return EXERCISES.filter(e => e.musclesSecondaires.includes(muscleId))
}

export function getExercisesByMode(mode: 'salle' | 'maison'): Exercise[] {
  return EXERCISES.filter(e => e.mode === mode || e.mode === 'les-deux')
}

export function getExercisesByMuscleAndMode(muscleId: MuscleId, mode: 'salle' | 'maison'): Exercise[] {
  return EXERCISES.filter(e =>
    e.musclesPrimaires.includes(muscleId) &&
    (e.mode === mode || e.mode === 'les-deux')
  )
}
